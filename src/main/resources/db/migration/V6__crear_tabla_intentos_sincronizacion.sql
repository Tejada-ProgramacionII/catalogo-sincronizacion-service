-- V6: registro de cada sincronización con la cátedra, para informar su estado (CU-06).
--
-- Una fila por sincronización: se abre al empezar (fin y resultado en NULL),
-- se actualiza al terminar cada intento fallido y se cierra con el resultado.
-- intentos cuenta los pedidos hechos a la cátedra (los reintentos incluidos).
-- mensaje es un motivo funcional, sin datos sensibles (D-11).
CREATE TABLE intentos_sincronizacion (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inicio           TIMESTAMP WITH TIME ZONE NOT NULL,
    fin              TIMESTAMP WITH TIME ZONE,
    resultado        VARCHAR(25),
    intentos         INTEGER                  NOT NULL,
    version_aplicada BIGINT,
    mensaje          VARCHAR(255),
    CONSTRAINT ck_intentos_sincronizacion_resultado
        CHECK (resultado IN ('OK', 'CATEDRA_NO_DISPONIBLE', 'RECHAZO', 'ERROR')),
    CONSTRAINT ck_intentos_sincronizacion_cierre
        CHECK ((fin IS NULL AND resultado IS NULL) OR (fin IS NOT NULL AND resultado IS NOT NULL))
);
